LANGUAGES = {'ja': '日本語', 'en': 'English'}
_language = 'ja'


def set_language(language):
    global _language
    _language = language if isinstance(language, str) and language in LANGUAGES else 'ja'


def get_language():
    return _language


def tr(text, *, context=None):
    """Translate an application string; unknown messages pass through intact."""
    if context == 'state' and text in ('終了', 'Ended'):
        return 'Ended' if _language == 'en' else '終了'
    if _language == 'en':
        summary = re.fullmatch(r'定期検索完了・今回(\d+)件を追加', text)
